/**
 * Control mode UI: the key legend bar, the move palette and the "E · Open ..." hint above the twin.
 * The engine (engine.ts) does the driving; this component only mounts it and renders its surroundings.
 * Loaded on demand the first time a visitor picks "Control me".
 */
import { useCallback, useEffect, useRef, useState } from 'react';
import { createPortal } from 'react-dom';
import { useLang, useT } from '../../../os/i18n/full';
import Sprite from '../../mascot/Sprite';
import type { PetApi } from './types';
import { createEngine, type Engine } from './engine';
import { PALETTE } from './moves';
import { readSeen } from './seen';
import './PetControl.css';

// EN/TR name of every move, generated by the sprite pipeline (scripts/sprites/labels.mjs)
const labelModules = import.meta.glob('../../../assets/sprites/mascot.labels.ts', { eager: true }) as Record<
  string,
  { ANIM_LABELS?: Record<string, { en: string; tr: string }> }
>;
const LABELS = Object.values(labelModules)[0]?.ANIM_LABELS ?? {};
const pretty = (a: string) => a.replace(/([A-Z])/g, ' $1').replace(/^./, (c) => c.toUpperCase());

export default function PetControl({ api }: { api: PetApi }) {
  const t = useT();
  const lang = useLang();
  const tRef = useRef(t);
  tRef.current = t;
  const hintRef = useRef<HTMLDivElement>(null);
  const engineRef = useRef<Engine | null>(null);
  const paletteRef = useRef(false);
  const [palette, setPaletteState] = useState(false);
  const [kbPet, setKbPet] = useState(true);
  const [seen, setSeen] = useState<ReadonlySet<string>>(() => new Set(readSeen()));

  const setPalette = useCallback((open?: boolean) => {
    const next = open ?? !paletteRef.current;
    paletteRef.current = next;
    setPaletteState(next);
    if (next) setSeen(new Set(readSeen())); // include what it did on its own meanwhile
  }, []);

  useEffect(() => {
    const engine = createEngine(api, {
      t: (key) => tRef.current(key),
      reduced: window.matchMedia?.('(prefers-reduced-motion: reduce)').matches ?? false,
      setPalette,
      isPaletteOpen: () => paletteRef.current,
      setKeyboard: setKbPet,
      onSeen: (s) => setSeen(new Set(s)),
      hintEl: () => hintRef.current,
    });
    engineRef.current = engine;
    engine.start();
    return () => {
      engine.stop();
      engineRef.current = null;
    };
  }, [api, setPalette]);

  const label = (a: string) => LABELS[a]?.[lang] ?? pretty(a);
  const found = PALETTE.filter((a) => seen.has(a)).length;

  return createPortal(
    <>
      <div className={`pet-ctl ${kbPet ? '' : 'pet-ctl--paused'}`} role="status">
        <span className="pet-ctl__title">🎮 {t('ctrlTitle')}</span>
        <span className="pet-ctl__keys">
          {kbPet ? (
            <>
              <kbd>←↑↓→</kbd> {t('ctrlWalk')} · <kbd>Shift</kbd> {t('ctrlRun')} · <kbd>Space</kbd> {t('ctrlJump')} · <kbd>E</kbd>{' '}
              {t('ctrlInteract')} · <kbd>M</kbd> {t('ctrlMoves')} · <kbd>Esc</kbd> {t('ctrlLetGo')}
            </>
          ) : (
            t('ctrlKeysWindow')
          )}
        </span>
        <button type="button" className="pet-ctl__btn" onClick={() => setPalette()} aria-expanded={palette}>
          {t('ctrlMoves')} {found}/{PALETTE.length}
        </button>
        <button type="button" className="pet-ctl__btn pet-ctl__btn--stop" onClick={() => api.exit()}>
          {t('ctrlLetGo')}
        </button>
      </div>

      {palette && (
        <div className="pet-ctl-palette" role="dialog" aria-label={t('ctrlPaletteTitle')}>
          <div className="pet-ctl-palette__head">
            <strong>{t('ctrlPaletteTitle')}</strong>
            <span>
              {found}/{PALETTE.length}
            </span>
            <button type="button" className="pet-ctl-palette__close" onClick={() => setPalette(false)} aria-label="Esc">
              ✕
            </button>
          </div>
          <p className="pet-ctl-palette__hint">{t('ctrlPaletteHint')}</p>
          <div className="pet-ctl-palette__grid">
            {PALETTE.map((a) => {
              const known = seen.has(a);
              return (
                <button
                  key={a}
                  type="button"
                  data-anim={a}
                  className={`pet-ctl-move ${known ? '' : 'is-locked'}`}
                  title={known ? label(a) : t('ctrlLocked')}
                  onClick={(e) => {
                    e.currentTarget.blur(); // Space must jump, not press this button again
                    engineRef.current?.perform(a);
                  }}
                >
                  <Sprite anim={a} scale={1} paused />
                  <span>{known ? label(a) : '???'}</span>
                </button>
              );
            })}
          </div>
        </div>
      )}

      <div ref={hintRef} className="pet-ctl-hint" hidden />
    </>,
    document.body
  );
}
